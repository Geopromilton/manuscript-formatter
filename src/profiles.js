export const profiles = Object.fromEntries(
  Object.entries({ ...journalProfiles, ...publisherProfiles }).map(([name, profile]) => {
    const source = profile.sourceUrl
      ? [profile.sourceName, profile.sourceUrl]
      : sources[profile.publisher]
    return [
      name,
      {
        ...profile,
        scope: profile.scope || 'publisher-template',
        status: profile.status || 'Publisher template',
        sourceName: source?.[0] || 'Official journal instructions needed',
        sourceUrl: source?.[1] || '',
        checkedDate: '2026-11-20',
        verified: profile.scope === 'journal',
      },
    ]
  }),
)
